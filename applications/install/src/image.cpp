#include "image.hpp"

bool installBootValidate(const uint8_t* boot, size_t length, const char** error)
{
	if(!boot || length != G_INSTALL_BOOT_SIZE || boot[510] != 0x55 || boot[511] != 0xaa)
	{
		*error = "invalid Limine boot files";
		return false;
	}

	return true;
}
