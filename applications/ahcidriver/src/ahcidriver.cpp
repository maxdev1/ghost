#include "ahcidriver.hpp"
#include <cstdio>
#include <libahci/driver.hpp>

int main()
{
	if(!g_task_register_name(G_AHCI_DRIVER_NAME))
		return -1;

	if(!ahciInitializeControllers())
		return -1;

	if(g_power_register(G_POWER_STORAGE) != G_POWER_SUCCESSFUL)
		return -1;

	ahciRegisterDevices();
	klog("ahci: block service ready");
	ahciReceiveMessages();
}
