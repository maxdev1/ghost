#include "ghost/syscall.h"
#include "ghost/tasks.h"
#include "ghost/tasks/callstructs.h"

g_bool g_time(int64_t* unixSeconds)
{
	if(!unixSeconds)
		return false;

	g_syscall_time data{-1};
	g_syscall(G_SYSCALL_GET_TIME, reinterpret_cast<g_address>(&data));
	*unixSeconds = data.unixSeconds;
	return data.unixSeconds >= 0;
}
